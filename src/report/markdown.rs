//! Markdown report: the format a human actually reads, and the one that gets
//! pasted into a bug bounty submission.

use std::fmt::Write;

use super::{Report, human_duration, md_cell};
use crate::findings::Finding;
use crate::models::Severity;
use crate::util::text::truncate;

/// Hosts listed in the attack-surface table.
const HOST_ROWS: usize = 100;

pub fn render(report: &Report<'_>) -> String {
    let summary = report.summary;
    let mut out = String::new();

    let _ = writeln!(out, "# BountyTool report — `{}`\n", summary.target);

    out.push_str("| | |\n|---|---|\n");
    row(&mut out, "Generated", &report.generated_at());
    row(&mut out, "Profile", &summary.profile);
    row(&mut out, "Duration", &human_duration(summary.elapsed_secs));
    row(&mut out, "Hosts", &summary.hosts.to_string());
    row(&mut out, "URLs", &summary.urls.to_string());
    row(&mut out, "Parameters", &summary.params.to_string());
    row(
        &mut out,
        "Findings",
        &format!(
            "{} primary, {} observations",
            report.primary().len(),
            report.observations().len()
        ),
    );
    row(&mut out, "Session", &format!("`{}`", summary.session_dir));
    out.push('\n');

    out.push_str("## Scope\n\n```\n");
    out.push_str(&report.scope.describe());
    out.push_str("\n```\n\n");
    let _ = writeln!(
        out,
        "> Scanning was performed on infrastructure the operator is authorised to test. \
         Reproduce these results only within the programme's rules.\n"
    );

    if !summary.by_severity.is_empty() {
        out.push_str("## Findings at a glance\n\n");
        out.push_str("| Severity | Count |\n|---|---|\n");
        for (severity, count) in &summary.by_severity {
            let _ = writeln!(out, "| {severity} | {count} |");
        }
        out.push('\n');
    }

    out.push_str("## Findings\n\n");
    if report.primary().is_empty() {
        out.push_str(
            "No finding passed the confidence threshold for this scan. \
                      The observations below are still worth a look.\n\n",
        );
    } else {
        for (index, finding) in report.primary().iter().enumerate() {
            render_finding(&mut out, index + 1, finding);
        }
    }

    if !report.observations().is_empty() {
        out.push_str("## Observations\n\n");
        out.push_str("Lower-confidence signals. Useful context, rarely a standalone bug.\n\n");
        out.push_str("| Severity | Category | Endpoint | Note |\n|---|---|---|---|\n");
        for finding in report.observations() {
            let _ = writeln!(
                out,
                "| {} | {} | `{}` | {} |",
                finding.severity.label(),
                finding.category.label(),
                md_cell(&finding.endpoint),
                md_cell(&truncate(&finding.title, 120))
            );
        }
        out.push('\n');
    }

    if !report.hosts.is_empty() {
        out.push_str("## Attack surface\n\n");
        out.push_str("| Status | URL | Title | Server | Tech |\n|---|---|---|---|---|\n");
        for host in report.hosts.iter().take(HOST_ROWS) {
            let _ = writeln!(
                out,
                "| {} | `{}` | {} | {} | {} |",
                host.status,
                md_cell(&host.url),
                md_cell(&truncate(&host.title, 60)),
                md_cell(&host.webserver),
                md_cell(&truncate(&host.tech.join(", "), 60))
            );
        }
        if report.hosts.len() > HOST_ROWS {
            let _ = writeln!(
                out,
                "\n_{} more hosts are listed in `artifacts/hosts.jsonl`._",
                report.hosts.len() - HOST_ROWS
            );
        }
        out.push('\n');
    }

    out.push_str("## Tooling\n\n");
    if summary.tools.is_empty() {
        out.push_str("No external tools were recorded; the scan used the native engine only.\n\n");
    } else {
        out.push_str("| Tool | Version |\n|---|---|\n");
        for tool in &summary.tools {
            let _ = writeln!(out, "| {} | {} |", tool.name, tool.version);
        }
        out.push('\n');
    }

    if !summary.degraded.is_empty() {
        out.push_str("### Degraded coverage\n\n");
        for note in &summary.degraded {
            let _ = writeln!(out, "- {note}");
        }
        out.push('\n');
    }

    out.push_str("---\n\n");
    let _ = writeln!(
        out,
        "Generated by {} {}. Findings are detection-only: verify manually before reporting.",
        crate::APP_NAME,
        crate::APP_VERSION
    );
    out
}

fn row(out: &mut String, key: &str, value: &str) {
    let _ = writeln!(out, "| **{}** | {} |", key, md_cell(value));
}

fn render_finding(out: &mut String, index: usize, finding: &Finding) {
    let _ = writeln!(
        out,
        "### {}. [{}] {}\n",
        index,
        finding.severity.label(),
        finding.title
    );

    out.push_str("| Field | Value |\n|---|---|\n");
    let category = match finding.cwe {
        Some(cwe) => format!("{} (CWE-{cwe})", finding.category.label()),
        None => finding.category.label().to_string(),
    };
    row(out, "Category", &category);
    row(out, "Host", &finding.host);
    row(out, "Endpoint", &format!("`{}`", finding.endpoint));
    if let Some(parameter) = &finding.parameter {
        row(out, "Parameter", parameter);
    }
    if let Some(payload) = &finding.payload {
        row(out, "Payload", &format!("`{}`", truncate(payload, 120)));
    }
    row(
        out,
        "Confidence",
        &format!("{} (score {:.2})", finding.confidence, finding.score),
    );
    if let Some(status) = finding.status {
        row(out, "Response", &status.to_string());
    }
    row(out, "Source", &finding.source.label());
    out.push('\n');

    out.push_str("**Impact**\n\n");
    let _ = writeln!(out, "{}\n", finding.category.impact());

    out.push_str("**Remediation**\n\n");
    let _ = writeln!(out, "{}\n", finding.category.remediation());

    if !finding.request.trim().is_empty() {
        out.push_str("**Evidence**\n\n```http\n");
        out.push_str(&truncate(&finding.request, 1_500));
        out.push_str("\n```\n\n");
    }
    if !finding.response_snippet.trim().is_empty() {
        out.push_str("```http\n");
        out.push_str(&truncate(&finding.response_snippet, 1_500));
        out.push_str("\n```\n\n");
    }
    if !finding.curl.trim().is_empty() {
        out.push_str("**Reproduce**\n\n```bash\n");
        out.push_str(&truncate(&finding.curl, 1_500));
        out.push_str("\n```\n\n");
    }
    if !finding.references.is_empty() {
        out.push_str("**References**\n\n");
        for reference in &finding.references {
            let _ = writeln!(out, "- {reference}");
        }
        out.push('\n');
    }
}

/// Kept public so the TUI can reuse the same severity ordering.
pub fn severity_rank(severity: Severity) -> u8 {
    match severity {
        Severity::Critical => 0,
        Severity::High => 1,
        Severity::Medium => 2,
        Severity::Low => 3,
        Severity::Info => 4,
    }
}
